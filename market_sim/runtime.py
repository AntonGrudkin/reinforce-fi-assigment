"""One-pass coordination; strategy callbacks never receive future market data."""

from collections.abc import Iterable, Iterator
from contextlib import nullcontext
from heapq import heappop, heappush
from pathlib import Path

from .data import ordered_events
from .execution import ExecutionEngine, ExecutionModel
from .history import (
    OrderEvent, PnlAttribution, PositionSnapshot, order_snapshot, save_history, save_order_history, snapshot,
)
from .models import (
    Event, Fill, FundingSettlement, LimitOrder, MarketEvent, MarketState,
    Number, OrderStatus, Portfolio, Side, TimerEvent, Trade, as_float, event_key, milliseconds_to_ns,
    quantities_close, round_to_step,
)


FUNDING_INTERVAL_NS = 8 * 60 * 60 * 1_000_000_000


def _bounded_events(events: Iterable[Event], end_timestamp_ns: int | None) -> Iterator[Event]:
    """Stop before generating settlements/commands beyond known book coverage."""
    for event in events:
        if end_timestamp_ns is not None and event.timestamp_ns > end_timestamp_ns:
            break
        yield event


def _with_settlements(events: Iterable[Event]) -> Iterator[Event]:
    """Insert UTC settlements inside the observed time range, including its ends.

    At a boundary, same-time books/rates precede settlement, trades follow it.
    Peeking ahead finds boundaries only; it never exposes that event's data.
    """
    next_settlement: int | None = None
    last_timestamp: int | None = None
    for event in ordered_events(events):
        if isinstance(event, FundingSettlement):
            raise ValueError("Funding settlements are generated by the runtime")
        if next_settlement is None:
            next_settlement = (
                (event.timestamp_ns + FUNDING_INTERVAL_NS - 1) // FUNDING_INTERVAL_NS
            ) * FUNDING_INTERVAL_NS
        while event_key(FundingSettlement(next_settlement)) <= event_key(event):
            yield FundingSettlement(next_settlement)
            next_settlement += FUNDING_INTERVAL_NS
        yield event
        last_timestamp = event.timestamp_ns
    # An input ending with just a book/rate at a boundary still settles there.
    if next_settlement is not None and next_settlement == last_timestamp:
        yield FundingSettlement(next_settlement)


class Strategy:
    """Override just the callbacks needed; place/cancel through the runtime."""

    def on_start(self, runtime: "BacktestEngine") -> None:
        pass

    def on_market_event(self, event: MarketEvent, runtime: "BacktestEngine") -> None:
        pass

    def on_timer(self, event: TimerEvent, runtime: "BacktestEngine") -> None:
        pass

    def on_fill(self, fill: Fill, runtime: "BacktestEngine") -> None:
        pass


class BacktestEngine:
    def __init__(
        self, strategy: Strategy, initial_cash: Number = 0,
        execution_model: ExecutionModel | None = None,
        maker_fee_rate: Number = 0,
        *, latency_ms: Number = 0,
    ) -> None:
        self.strategy = strategy
        self.state = MarketState()
        self.portfolio = Portfolio(initial_cash, maker_fee_rate)
        self.execution = ExecutionEngine(self.portfolio)
        if execution_model is not None:
            self.execution.model = execution_model
        self._started = False
        self.history: list[PositionSnapshot] = []
        self.order_history: list[OrderEvent] = []
        self._attribution = PnlAttribution()
        # Full request-completion delay (roundtrip), applied equally to place/cancel.
        # Market data and accounting/fill callbacks remain immediate in this MVP.
        self.latency_ns = milliseconds_to_ns(latency_ms)
        self._commands: list[tuple[int, int, str, int]] = []
        self._command_sequence = 0
        self._pending_cancels: set[int] = set()
        self._inventory_limit_fraction: float | None = None
        self._inventory_quantity_step: float | None = None

    def set_inventory_limit(self, equity_fraction: Number, *, quantity_step: Number | None = None) -> None:
        """Register the strategy's existing marked-equity inventory constraint."""
        fraction = as_float(equity_fraction)
        if fraction <= 0:
            raise ValueError('Inventory limit fraction must be positive')
        step = as_float(quantity_step) if quantity_step is not None else None
        if step is not None and step <= 0:
            raise ValueError('Quantity step must be positive')
        self._inventory_limit_fraction = fraction
        self._inventory_quantity_step = step

    def order_capacity(self, side: Side, *, exclude_order_id: int | None = None) -> float:
        """Worst-case same-side fills, without assuming opposite-side fills/cancels."""
        if self._inventory_limit_fraction is None:
            return float('inf')
        mark = self.state.mark_price
        if mark is None or mark <= 0 or self.equity <= 0:
            return 0.0
        maximum = self._inventory_limit_fraction * self.equity / mark
        headroom = maximum - self.portfolio.inventory if side == Side.BUY else maximum + self.portfolio.inventory
        reserved = self.execution.reserved_quantity(side, exclude_order_id=exclude_order_id)
        return max(0.0, headroom - reserved)

    def _reserve_order(self, order: LimitOrder) -> bool:
        capacity = self.order_capacity(order.side, exclude_order_id=order.order_id)
        if order.remaining_quantity > capacity and self._inventory_quantity_step is not None:
            rounded = round_to_step(capacity, self._inventory_quantity_step)
            # Strategy grid rounding tolerates a billionth of a step. A risk cap
            # must never use that tolerance to manufacture extra capacity.
            if rounded > capacity and not quantities_close(rounded, capacity):
                rounded = round_to_step(max(0.0, rounded - self._inventory_quantity_step),
                                        self._inventory_quantity_step)
            capacity = rounded
        if capacity <= 0:
            self.execution.reject(order.order_id, 'inventory_capacity')
            return False
        if order.remaining_quantity > capacity:
            # Only pending orders reach this method; no executed quantity changes.
            order.original_quantity = order.remaining_quantity = capacity
        return True

    def _activate_order(self, order: LimitOrder, *, record_snapshot: bool = True) -> None:
        # Recheck risk and passivity using the state at command completion.
        accepted = self._reserve_order(order) and self.execution.activate(
            order.order_id, self.state.book, self.state.timestamp_ns)
        event = 'place' if accepted else 'reject'
        self._record_order(order, event)
        if record_snapshot or not accepted:
            self._record_snapshot(f'order_{event}')

    def place_order(self, side: Side, price: Number, quantity: Number) -> LimitOrder:
        if self.state.timestamp_ns is None:
            raise ValueError("Orders require a current event timestamp")
        order = self.execution.place(side, price, quantity, self.state.timestamp_ns + self.latency_ns,
                                     activate=False)
        if not self._reserve_order(order):
            self._record_order(order, 'reject')
            self._record_snapshot('order_reject')
            return order
        if self.latency_ns:
            self._schedule_command("place", order.order_id)
        else:
            self._activate_order(order, record_snapshot=False)
        return order

    def cancel_order(self, order_id: int) -> bool:
        """Return whether a cancel request was accepted; it may lose a race to a fill."""
        order = self.execution.orders[order_id]
        if not order.is_live or order_id in self._pending_cancels:
            return False
        if self.latency_ns:
            self._pending_cancels.add(order_id)
            self._schedule_command("cancel", order_id)
            return True
        cancelled = self.execution.cancel(order_id)
        if cancelled:
            self._record_order(self.execution.orders[order_id], "cancel")
        return cancelled

    def _schedule_command(self, action: str, order_id: int) -> None:
        self._command_sequence += 1
        heappush(self._commands, (self.state.timestamp_ns + self.latency_ns,
                                 self._command_sequence, action, order_id))

    def _process_commands(self, until_ns: int, *, include_endpoint: bool = False) -> None:
        """Equal-time historical events run first; commands are FIFO at ties.

        Advance only the clock, retaining the latest already-observed market data.
        Commands in gaps still take effect at their exact nanosecond deadline.
        """
        while self._commands:
            timestamp_ns = self._commands[0][0]
            if timestamp_ns > until_ns or (timestamp_ns == until_ns and not include_endpoint):
                break
            _, _, action, order_id = heappop(self._commands)
            self.state.timestamp_ns = timestamp_ns
            order = self.execution.orders[order_id]
            if action == "place":
                if order.status != OrderStatus.PENDING_NEW:
                    continue
                self._activate_order(order)
                continue
            else:
                self._pending_cancels.remove(order_id)
                if not self.execution.cancel(order_id):
                    continue  # Filled while the cancel request was in flight.
            self._record_order(order, action)
            self._record_snapshot(f"order_{action}")

    @property
    def equity(self) -> float:
        return self.portfolio.equity(self.state.mark_price)

    @property
    def pnl(self) -> float:
        return self.portfolio.pnl(self.state.mark_price)

    def save_history(self, path: str | Path) -> None:
        save_history(path, self.history)

    def save_order_history(self, path: str | Path) -> None:
        save_order_history(path, self.order_history)

    def _record_order(self, order: LimitOrder, event: str, fill: Fill | None = None) -> None:
        self.order_history.append(order_snapshot(
            self.state, order, event, len(self.order_history) + 1, fill,
        ))

    def _record_fill(self, fill: Fill) -> None:
        self._record_order(self.execution.orders[fill.order_id], "fill", fill)
        self._record_snapshot("fill", fill=fill)

    def _record_snapshot(
        self, event: str, *, fill: Fill | None = None, funding_payment: float = 0.0,
    ) -> None:
        self.history.append(snapshot(self.state, self.portfolio, event, fill=fill,
                                     funding_payment=funding_payment, attribution=self._attribution))

    def run(
        self, events: Iterable[Event], *, progress: bool = False,
        total_events: int | None = None,
        end_timestamp_ns: int | None = None,
    ) -> "BacktestEngine":
        """Run once. Update state, apply all trade fills, notify fills, then market.

        on_start sees an empty state. Same-trade callback actions cannot affect
        that trade's fills. Explicit TimerEvents can be merged with market streams.
        Funding settlements are generated automatically on the UTC eight-hour grid.
        Orders activate only if still passive; visible same-level depth initializes
        their queue ahead. Registered inventory limits reserve all live same-side
        remaining quantities, including pending placements and cancellations.
        History captures each event and each fill before strategy callbacks.
        Outstanding orders remain open at the end; there is no forced liquidation.
        With latency, commands take effect after latency_ns; at ties historical
        events precede commands. Pending commands past the input end stay pending.
        EventWindow inputs automatically cap the run at their effective end. Pass
        end_timestamp_ns explicitly when wrapping that iterator (e.g. for counting).
        Later inputs, generated settlements and commands are never processed.
        Optional tqdm progress counts supplied events only, excluding generated
        settlements/commands. Supply total_events for lazy streams to show an ETA;
        without a known total, tqdm shows event count, elapsed time and throughput.
        """
        if self._started:
            raise RuntimeError("Create a new BacktestEngine for each run")
        if total_events is not None and total_events < 0:
            raise ValueError("Total event count must be nonnegative")
        window_end = getattr(events, 'end_timestamp_ns', None)
        if window_end is not None:
            end_timestamp_ns = window_end if end_timestamp_ns is None else min(end_timestamp_ns, window_end)
        events = _bounded_events(events, end_timestamp_ns) if end_timestamp_ns is not None else events
        if progress:
            try:
                from tqdm import tqdm
            except ImportError as error:
                raise ImportError("Progress bars require tqdm: pip install -e '.[progress]'") from error
            event_source = tqdm(events, total=total_events, desc="Backtest", unit="event", dynamic_ncols=True)
        else:
            event_source = nullcontext(events)
        # Close the bar on normal completion, callback errors or interruption.
        with event_source as stream:
            self._started = True
            self._record_snapshot("initial")
            self.strategy.on_start(self)
            for event in _with_settlements(stream):
                self._process_commands(event.timestamp_ns)
                self.state.update(event)
                funding_payment = 0.0
                if isinstance(event, FundingSettlement):
                    rate = self.state.funding.funding_rate if self.state.funding else None
                    funding_payment = self.portfolio.apply_funding(self.state.mark_price, rate)
                if isinstance(event, TimerEvent):
                    self._record_snapshot("timer")
                    self.strategy.on_timer(event, self)
                    continue
                if isinstance(event, Trade):
                    # Finish matching/accounting before callbacks can place/cancel orders.
                    fills = self.execution.process_trade(event, on_applied=self._record_fill)
                self._record_snapshot(type(event).__name__, funding_payment=funding_payment)
                if isinstance(event, Trade):
                    for fill in fills:
                        self.strategy.on_fill(fill, self)
                self.strategy.on_market_event(event, self)
            if self.state.timestamp_ns is not None:
                self._process_commands(self.state.timestamp_ns, include_endpoint=True)
        return self
